# -*- coding: utf-8 -*-
"""
MCQ VALIDATOR AGENT v3 — Standalone validation using pipeline.mcq_validator
This agent validates MCQs generated by Agent 16 with additional checks.
"""
import logging

COMMAND = "Validate MCQs for quality, correctness, and exam-readiness."
MASTER_RULE = "Student Value First. Accuracy Before Speed. Quality Before Quantity."


class Agent:
    def __init__(self, job_id, job_type, context):
        self.job_id = job_id
        self.job_type = job_type
        self.context = context
        self.name = "MCQ VALIDATOR AGENT v3"

    def run(self):
        from pipeline.state import MCQ_DIR, CONTENT_DIR, data_path, read_json, write_json_atomic
        
        mcqs = read_json(data_path(MCQ_DIR, self.job_id), [])
        content = read_json(data_path(CONTENT_DIR, self.job_id))
        items = content.get("items", [])
        
        if not mcqs:
            self.context["stage_failed"] = "No MCQs to validate"
            raise RuntimeError(self.context["stage_failed"])
        
        logging.info(f"[{self.name}] Validating {len(mcqs)} MCQs...")
        
        # Use new mcq_validator for additional validation
        validated_mcqs = []
        validation_method = "none"
        
        try:
            from pipeline.mcq_validator import validate_mcqs
            
            logging.info(f"[{self.name}] Running mcq_validator...")
            validated_mcqs = validate_mcqs(mcqs, items)
            validation_method = "mcq_validator_v2"
            
            rejected = len(mcqs) - len(validated_mcqs)
            logging.info(f"[{self.name}] Validation: {len(validated_mcqs)}/{len(mcqs)} passed ({rejected} rejected)")
            
        except ImportError as e:
            logging.warning(f"[{self.name}] mcq_validator not available: {e}")
            logging.info(f"[{self.name}] Using existing validation (fallback)")
            
            # Fallback to old validation
            try:
                from pipeline.content import validate_mcqs as old_validate
                validated_mcqs = old_validate(mcqs)
                validation_method = "old_validate_fallback"
            except Exception as e2:
                logging.warning(f"[{self.name}] Old validation also failed: {e2}")
                validated_mcqs = mcqs  # Use as-is
                validation_method = "no_validation"
            
        except Exception as e:
            logging.error(f"[{self.name}] Validation failed: {e}")
            validated_mcqs = mcqs
            validation_method = "no_validation"
        
        # Quality gate
        min_mcqs = min(8, len(items))
        
        if len(validated_mcqs) < min_mcqs:
            self.context["stage_failed"] = f"only {len(validated_mcqs)} valid MCQs (need >={min_mcqs})"
            raise RuntimeError(self.context["stage_failed"])
        
        # Save validated MCQs
        write_json_atomic(data_path(MCQ_DIR, self.job_id), validated_mcqs)
        
        logging.info(f"[{self.name}] Complete: {len(validated_mcqs)} MCQs using {validation_method}")
        self.context["mcqs_validated"] = len(validated_mcqs)
        self.context["validation_method"] = validation_method
        
        return self.context

    def verify(self):
        return not self.context.get("stage_failed")


if __name__ == "__main__":
    import logging
    logging.basicConfig(level=logging.INFO)
    ctx = {"job_id": "test_2026-10-12", "job_type": "daily", "job_date": "2026-10-12"}
    print(Agent("test_2026-10-12", "daily", ctx).run())
